clc
close all 

%getting data 

%this is the location of Ludhiana, an agricultural hub in Punjab, India

filename = 'punjab_agro.csv';
lat = 30.90;
lon = 75.85;

if ~isfile(filename) %checking if file already exists
    params = 'T2M_MAX,PRECTOTCORR,GWETROOT';

    url = sprintf(['https://power.larc.nasa.gov/api/temporal/monthly/point?' ...
        'parameters=%s&community=AG&longitude=%.4f&latitude=%.4f' ...
        '&start=2001&end=2025&format=CSV'], params, lon, lat);

    disp('Downloading data from NASA POWER...');
    websave(filename, url);
    disp('Download complete! Saved to punjab_agro.csv');
else
    disp('punjab_agro.csv already exists, skipping download :).');
end

%vegetation health: 
ndviFile = 'punjab_ndvi.csv';
if ~isfile(ndviFile)
    disp('Fetching valid MODIS MOD13Q1 dates...');
    options = weboptions('ContentType', 'json', 'Timeout', 60);

    datesUrl = sprintf('https://modis.ornl.gov/rst/api/v1/MOD13Q1/dates?latitude=%.4f&longitude=%.4f', lat, lon);
    dateInfo = webread(datesUrl, options);
    allCodes = string({dateInfo.dates.modis_date});

    yrNum = str2double(extractBetween(allCodes, 2, 5));
    validCodes = allCodes(yrNum >= 2001 & yrNum <= 2025);

    ndviDates = NaT(0, 1);
    ndviVals  = nan(0, 1);
    batchSize = 10;
    totalBatches = ceil(length(validCodes) / batchSize);

    for k = 1:batchSize:length(validCodes)
        batchNum = ceil(k / batchSize);
        fprintf('Downloading NDVI batch %d of %d...\n', batchNum, totalBatches);

        sDate = validCodes(k);
        eDate = validCodes(min(k + batchSize - 1, length(validCodes)));

        url = sprintf(['https://modis.ornl.gov/rst/api/v1/MOD13Q1/subset?' ...
            'latitude=%.4f&longitude=%.4f&band=250m_16_days_NDVI' ...
            '&startDate=%s&endDate=%s&kmAboveBelow=0&kmLeftRight=0'], ...
            lat, lon, sDate, eDate);
        res = webread(url, options);

        nObs = length(res.subset);
        chunkDates = NaT(nObs, 1);
        chunkVals  = nan(nObs, 1);
        for i = 1:nObs
            chunkDates(i) = datetime(res.subset(i).calendar_date, 'InputFormat', 'yyyy-MM-dd');
            rawPixels = double(res.subset(i).data);
            rawPixels(rawPixels < -2000) = NaN;
            chunkVals(i) = mean(rawPixels, 'omitnan') * 0.0001;
        end
        ndviDates = [ndviDates; chunkDates]; %#ok<AGROW>
        ndviVals  = [ndviVals; chunkVals];   %#ok<AGROW>
    end

    writetable(table(ndviDates, ndviVals, 'VariableNames', {'Date', 'NDVI'}), ndviFile);
    disp('Download complete! Saved to punjab_ndvi.csv');
else
    disp('punjab_ndvi.csv already exists, skipping download :).');
end
%parsing the data 

%first finding where the data starts
lines = readlines(filename);
header = find(startsWith(lines, 'PARAMETER'));
opts = detectImportOptions(filename, 'NumHeaderLines', header - 1);
raw_table = readtable(filename, opts); 

%now replacing >999 with NaN and getting the months across 2001 - 2025
months_p = {'JAN','FEB','MAR','APR','MAY','JUN','JUL','AUG','SEP','OCT','NOV','DEC'};
dataMat = raw_table{:,months_p};
dataMat(dataMat <= -990) = NaN;
raw_table{:, months_p} = dataMat;

%parameter names so that they are intuitive:
paramCodes  = {'T2M_MAX', 'PRECTOTCORR', 'GWETROOT', 'MODIS_NDVI'};
paramTitles = { ...
    'Max 2m Air Temperature (Heat Stress)', ...
    'Corrected Precipitation (Monsoon Supply)', ...
    'Root Zone Soil Wetness (Crop Water Availability)', ...
    'MODIS NDVI (Satellite Vegetation Health)'}; 
paramUnits  = {'°C', 'mm/day', 'fraction (0–1)', 'NDVI (-1 to +1)'}; 

%vegetation parsing: 
ndviRaw = readtable(ndviFile);
ndviTT  = retime(table2timetable(ndviRaw), 'monthly', 'mean');
ndviMonthlyDates = datetime(year(ndviTT.Date), month(ndviTT.Date), 15);
ndviMonthlyVals  = ndviTT.NDVI;

%colours for the plots, generated by gemini so that they are a little
%intuitive to those that are not colour blind. 
trendCol =[
    0.85, 0.25, 0.15;   % Red-Orange: Temperature
    0.00, 0.45, 0.74;   % Ocean Blue: Precipitation
    0.55, 0.35, 0.17;   % Earth Brown: Soil Wetness
    0.13, 0.55, 0.13    % Forest Green: MODIS NDVI  <-- Added 4th row
];
rawColours = trendCol + 0.55 * (1 - trendCol);

%plotting the data to identify trends over the last 25 years

figure('Name', 'KisanTrend: Punjab Agroclimatology Trends', 'Color', 'w', 'Position', [100, 100, 1100, 800]);

for p = 1:length(paramCodes) %going through each variable, should give 3 plots (to match the number of parameters)
    code = paramCodes{p};

    %flattening the data for each month of each year 
    if strcmp(code, 'MODIS_NDVI')
        dates = ndviMonthlyDates;
        vals  = ndviMonthlyVals;
    else
        sub = sortrows(raw_table(strcmp(raw_table.PARAMETER, code), :), 'YEAR');
        tYears = sub.YEAR;
        vals  = reshape(sub{:, months_p}', [], 1);
        dates = datetime(repelem(tYears, 12), repmat((1:12)', length(years), 1), 15);
    end
    
    %removing NaNs, for incompelete years 
    valid = ~isnan(vals); %mask for non NaN values
    vals = vals(valid);
    dates = dates(valid);
    tYears = tYears(valid);
    months = month(dates);

    %now finding any annomalies, e.g. a heavier monsoon season

    anomalies = zeros(size(vals));

    for m = 1:12
        idx = (months == m); 
        anomalies(idx) = vals(idx) - mean(vals(idx), 'omitnan'); %finding annomalies by removing the average
    end

    %linear regression for rate of change per year, 95% CI, t-test

    mdl = fitlm(tYears, anomalies);
    slope = mdl.Coefficients.Estimate(2);
    t_pval = mdl.Coefficients.pValue(2);
    ci = coefCI(mdl);
    slopeCI = (ci(2,2) - ci(2,1))/2;

    %Mann-Kendall Non-Parametric Trend Test

    [tau, mk_pval] = corr(tYears,anomalies, 'Type','Kendall');

    %readable command report to window: 
    fprintf('=== %s (%s) ===\n', paramTitles{p}, code);
    fprintf('  Rate of Change : %+.4f %s/year (±%.4f 95%% CI)\n', slope, paramUnits{p}, slopeCI);
    fprintf('  t-test p-value : %.4e  (%s)\n', t_pval, sigLabel(t_pval));
    fprintf('  Mann-Kendall   : tau = %+.3f, p = %.4e (%s)\n\n', tau, mk_pval, sigLabel(mk_pval));

    subplot(4,1,p); %finally, the plot
    plot(dates, anomalies,'Color',rawColours(p, :), 'LineWidth',3)
    hold on 
    [yFit, yCI] = predict(mdl, tYears);
    fill([dates; flipud(dates)], [yCI(:,1); flipud(yCI(:,2))],trendCol(p, :), 'FaceAlpha', 0.15, 'EdgeColor', 'none')
    plot(dates, yFit,'Color',trendCol(p, :),'LineWidth',3)
    yline(0, '--k', 'Alpha', 0.4);
    title(sprintf('%s — Slope: %+.4f %s/yr | t-test p = %.3g | MK p = %.3g', ...
        paramTitles{p}, slope, paramUnits{p}, t_pval, mk_pval), 'FontWeight', 'bold');
    ylabel(['Anomaly (' paramUnits{p} ')']);
    xlim([datetime(2001,1,1), datetime(2025,12,31)]);
    grid on;

end

exportgraphics(gcf, 'punjab_trends_summary.png', 'Resolution', 300);
disp('Saved high-res figure to punjab_trends_summary.png');

function label = sigLabel(p)
    if p < 0.05
        label = 'STATISTICALLY SIGNIFICANT (p<0.05)';
    else
        label = 'NOT SIGNIFICANT AT >95% LEVEL';
    end
end